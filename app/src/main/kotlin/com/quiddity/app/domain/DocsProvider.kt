五、模型配置怎么填
在设置或会话菜单里进入"管理模型配置"，点新增：
1. 选择服务商，比如 DeepSeek、智谱、通义千问。选好后接口地址和模型名会自动填好。
2. 填 API 密钥。密钥去服务商官网的密钥页面创建，具体步骤看文档里的"API-KEY 获取方式"。
3. 保存后把这个配置设为当前使用。
如果服务商列表里没有你用的，选"自定义"，接口地址、模型名、密钥全部自己填。

六、主动消息和时间库
完整流程：
1. 先在设置里打开"主动消息"总开关（这一步只是让你了解功能）。
2. 进入你想开启的会话，在右上角菜单的"主动消息"里单独打开这个会话的开关。
3. 开启时会提示正在生成今日时间库，完成后会告诉你今天有哪些时间点。
4. 到点后，App 会在这个会话里发一条 AI 消息，同时通知栏弹出通知，点通知回到 App。
想查看今天的时间安排，点"查看时间库"。如果设置了密码，输入 AI 制定的密码即可。时间会显示成"下午 1:30"这种一看就懂的说法。
为了确保到点能触发，建议：给 App 打开电池优化的"不受限制"，在 Android 12 及以上允许"闹钟和提醒"，国产手机还要允许自启动。

七、备份和恢复
设置页的"数据导出"可以把全部数据（设置、所有会话、消息、AI 头像、壁纸、时间库设置）保存成一个文件，放在手机本地或云盘。需要恢复时用"数据导入"选择这个文件，可以选择替换现有数据、合并数据、或只导入角色库。建议定期备份，尤其是更新大版本之前。
单个会话可以单独导出人设卡或对话记录，随时导入回来。

八、常见问题
- AI 不回消息：先检查模型配置里的密钥和接口地址是否正确，网络是否可用。
- 主动消息一直没收到：检查是否在具体会话里单独开启了主动消息、模型接口是否可用、通知权限是否打开、电池优化是否放行。
- 聊天记录会不会丢：聊天记录都存在手机本地，导出备份后换手机也能恢复。
- 撤回和删除不可恢复：删除前请想清楚，重要内容先备份。
